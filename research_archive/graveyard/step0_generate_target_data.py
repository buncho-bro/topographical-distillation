import os
import pickle
import random

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
OUTPUT_PATH = os.path.join(BASE_DIR, "target_texts.pkl")

# (文脈となる文のテンプレート, ターゲットとなる単語)
# 概念の種類を大幅に増やし、空間全体をカバーできるようにする
concepts = [
    ("動物", ["犬は最も身近な{t}の一つである。", "地球上には多様な{t}が生息している。", "生物学において{t}の分類は重要だ。"]),
    ("植物", ["道端に小さな{t}が生えていた。", "{t}は光合成によって酸素を生み出す。", "森林には無数の{t}が自生している。"]),
    ("科学", ["{t}の発展が人類の歴史を変えた。", "現代の{t}は驚くべきスピードで進歩している。", "物理学は{t}の基礎的な分野である。"]),
    ("感情", ["強い{t}に揺さぶられ、彼は涙を流した。", "人間は複雑な{t}を持つ生き物だ。", "心理学は人間の{t}を研究する学問である。"]),
    ("政治", ["この国の{t}は混迷を極めている。", "{t}の決断が世界経済に影響を与える。", "民主主義は{t}の一つの形態である。"]),
    ("宇宙", ["広大な{t}の果てには何があるのだろうか。", "{t}の起源はビッグバンにあるとされている。", "人類は常に{t}の謎を解き明かそうとしてきた。"]),
    ("芸術", ["その絵画は{t}の傑作として評価されている。", "{t}は言葉を超えて人の心を動かす。", "歴史的な建築物もまた{t}の一形態である。"]),
    ("機械", ["工場には巨大な{t}が設置されている。", "AIの進化により{t}は自律的に動くようになった。", "この{t}は非常に複雑な構造をしている。"]),
    ("経済", ["{t}の動向が社会全体に影響を及ぼす。", "市場における{t}の役割は極めて大きい。", "インフレーションは{t}の現象の一つである。"]),
    ("歴史", ["古代の{t}を学ぶことは未来を知ることに繋がる。", "教科書には多くの{t}が記されている。", "人類の{t}は戦争と平和の繰り返しである。"]),
    ("数学", ["{t}は宇宙の言語とも呼ばれる。", "この方程式は{t}の美しい証明である。", "幾何学は{t}の基礎的な学問である。"]),
    ("物理", ["量子力学は現代の{t}において不可欠だ。", "{t}の法則は絶対的なものである。", "アインシュタインは{t}の概念を覆した。"]),
    ("宗教", ["多くの人々が{t}に救いを求めてきた。", "{t}は文化と密接に結びついている。", "世界には多様な{t}が存在する。"]),
    ("教育", ["子供たちにとって{t}は最も重要な権利だ。", "{t}の質が国の未来を左右する。", "学校は{t}を提供する場である。"]),
    ("医療", ["最新の{t}により多くの命が救われている。", "{t}の現場では常に倫理が問われる。", "ワクチンの開発は{t}の大きな進歩だ。"]),
    ("言語", ["{t}はコミュニケーションの基本的なツールである。", "世界には数千の{t}が存在する。", "{t}の壁を越えることが相互理解に繋がる。"])
]

def generate_data():
    print("Generating Massive Targeted Context Dataset...")
    dataset = []
    
    for target, templates in concepts:
        for _ in range(25): # 16概念 × 25件 = 400件
            template = random.choice(templates)
            adj = random.choice(["一般的に言って、", "専門家によれば、", "驚くべきことに、", "歴史を振り返ると、", "最新の研究では、", "しばしば、", "多くの人が信じるように、"])
            text = f"{adj}{template.format(t=target)}"
            dataset.append({"text": text, "target": target})
            
    random.shuffle(dataset)
    
    with open(OUTPUT_PATH, "wb") as f:
        pickle.dump(dataset, f)
        
    print(f"Generated {len(dataset)} targeted texts successfully!")
    print("Samples:")
    for d in dataset[:3]:
        print(f" - Text: {d['text']}")
        print(f"   Target: {d['target']}")
    print(f"\nSaved to: {OUTPUT_PATH}")

if __name__ == "__main__":
    generate_data()
